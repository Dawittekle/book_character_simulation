def sync_seed_avatar_catalog(session: Session) -> list[AvatarAsset]:
    """Ensures that the curated approved avatar library is populated in the database."""
    items: list[AvatarAsset] = []
    for avatar_dict in SEED_AVATAR_CATALOG:
        existing = session.scalar(
            select(AvatarAsset).where(AvatarAsset.asset_id == avatar_dict["asset_id"])
        )
        if existing is None:
            item = AvatarAsset(**avatar_dict)
            session.add(item)
            items.append(item)
        else:
            items.append(existing)
    session.flush()
    return items
